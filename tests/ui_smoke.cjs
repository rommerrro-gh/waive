const assert = require("node:assert/strict");
const { readFile } = require("node:fs/promises");
const { chromium } = require("playwright");

async function main() {
  const browser = await chromium.launch({
    executablePath: process.env.CHROME_BIN,
    headless: true,
    args: ["--no-sandbox"],
  });
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
    page.on("pageerror", error => { throw error; });
    await page.goto(new URL("/?demo=true", process.env.WAIVE_TEST_URL || "http://127.0.0.1:8000").href);
    const input = page.getByRole("combobox", {name: "Название, бренд или артикул"});
    assert.equal(await input.getAttribute("aria-describedby"), "search-help");
    await page.getByText(/Начните вводить название или артикул/).waitFor();
    const filters = page.locator("#search-filters > summary");
    const stock = page.getByRole("checkbox", {name: "В наличии"});
    assert.equal(await stock.isVisible(), false);
    await filters.click();
    assert.equal(await stock.isVisible(), true);
    assert.equal(await page.getByRole("spinbutton", {name: "Цена от, ₽"}).isVisible(), true);
    await filters.click();
    assert.equal(await stock.isVisible(), false);
    await input.fill("впн");
    await page.getByRole("option", {name: "VPN", exact: true}).waitFor();
    await input.press("Enter");
    await page.getByText("Запрос распознан как «VPN».", {exact: true}).waitFor();
    await page.locator("#results article").first().waitFor();
    const [typo, brand] = process.env.WAIVE_E5_SMOKE === "1"
      ? ["адинэсс", "AnyDesk"] : ["майкрасавт", "Microsoft"];
    await input.fill(typo);
    await page.getByRole("option", {name: brand, exact: true}).waitFor();
    await input.press("Enter");
    await page.getByText("Возможно, вы имели в виду", {exact: true}).waitFor();
    await page.locator("#spelling-options").getByRole("button", {name: brand, exact: true}).click();
    await page.locator("#results article h2").filter({hasText: brand}).first().waitFor();
    await input.fill("125344");
    await input.press("Enter");
    await page.getByText("Точного товара нет в наличии. Найдены альтернативы", {exact: true}).waitFor();
    assert.equal(await page.locator("#alternatives article").count(), 4);
    await input.fill("460304");
    await input.press("Enter");
    await page.locator("#results article").first().getByRole("button", {name: "Подобрать дополнения"}).click();
    await page.locator("#bundle").getByText(/Совпадает интерфейс: usb/i).first().waitFor();
    assert.equal(await page.locator("#bundle").getByRole("button", {name: "На согласование"}).count(), 0);
    await input.fill("майкр");
    await input.press("Escape");
    await page.waitForTimeout(350);
    assert.equal(await input.inputValue(), "майкр");
    assert.equal(await input.getAttribute("aria-expanded"), "false");
    await input.fill("???");
    await input.press("Enter");
    await page.getByText("Введите название, бренд или артикул от двух символов.", {exact: true}).waitFor();
    await input.evaluate(field => {
      field.value = "фтнвуыл";
      field.dispatchEvent(new InputEvent("input", {bubbles: true, isComposing: true}));
      field.dispatchEvent(new CompositionEvent("compositionend", {bubbles: true}));
    });
    await page.getByRole("option", {name: "AnyDesk", exact: true}).waitFor();
    await input.clear();
    assert.equal(await input.getAttribute("aria-expanded"), "false");
    await input.fill("Качперкский");
    await page.getByRole("option", {name: "Kaspersky", exact: true}).waitFor();
    await page.getByRole("button", {name: "Найти", exact: true}).click();
    await page.getByText("Запрос распознан как «Kaspersky».", {exact: true}).waitFor();
    await input.fill("каспер");
    await page.getByRole("option", {name: "Kaspersky", exact: true}).waitFor();
    await input.press("ArrowDown");
    await input.press("Enter");
    assert.equal(await input.inputValue(), "Kaspersky");
    const more = page.getByRole("button", {name: "Показать ещё", exact: true});
    const cards = page.locator("#results article");
    await more.waitFor();
    assert.equal(await cards.count(), 12);
    await input.fill("майкр");
    await page.getByRole("option", {name: /Microsoft/}).first().waitFor();
    await input.press("Escape");
    const firstPage = await cards.locator("h2").allTextContents();
    await more.click();
    assert.ok(await cards.count() > firstPage.length);
    assert.deepEqual((await cards.locator("h2").allTextContents()).slice(0, 12), firstPage);
    await input.fill("касперчкий");
    await page.getByRole("button", {name: "Найти", exact: true}).click();
    await page.getByText("Запрос распознан как «Kaspersky».", {exact: true}).waitFor();
    assert.equal(await cards.count(), 12);
    const sort = page.getByRole("combobox", {name: "Сортировка"});
    await sort.selectOption("price-asc");
    const prices = (await cards.locator(".product-offer strong").allTextContents())
      .map(label => Number(label.replace(/[^0-9,]/g, "").replace(",", ".")));
    assert.ok(prices.every((value, index) => index === 0 || value >= prices[index - 1]));
    await sort.selectOption("relevance");
    await filters.click();
    const categories = page.locator("#category-options input");
    assert.ok(await categories.count() > 1);
    await categories.first().check();
    assert.ok(await cards.count() < 12);
    await page.getByRole("button", {name: "Сбросить фильтры"}).click();
    await cards.nth(11).waitFor();
    assert.equal(await page.locator("#category-options input:checked").count(), 0);
    await filters.click();
    await input.fill("крипто пр");
    await page.getByRole("option", { name: /КриптоПро CSP TLS/i }).waitFor();
    assert.equal(await input.getAttribute("aria-expanded"), "true");
    await input.press("Escape");
    assert.equal(await input.getAttribute("aria-expanded"), "false");

    await input.fill("AnyD");
    await page.getByRole("option", { name: "AnyDesk", exact: true }).waitFor();
    await input.press("ArrowDown");
    const active = await input.getAttribute("aria-activedescendant");
    assert.ok(active);
    const selectedName = await page.locator("#" + active).textContent();
    await input.press("Enter");
    assert.equal(await input.inputValue(), selectedName);
    await page.locator("#results article").first().waitFor();
    await input.fill("антивирус для рабочих станций компании");
    await page.getByRole("button", { name: "Найти" }).click();
    await page.locator("#results article").nth(2).waitFor();
    assert.equal(await page.getByRole("button", {name: "На согласование"}).count(), 0);
    const buttons = page.locator("#results .compare-toggle");
    const compareMenu = page.locator("#toggle-comparison");
    assert.equal(await compareMenu.isVisible(), false);
    assert.equal(await buttons.first().evaluate(button => getComputedStyle(button).backgroundColor), "rgb(239, 239, 241)");
    await buttons.nth(0).click();
    assert.equal(await compareMenu.innerText(), "Сравнение (1 из 4)");
    assert.equal(await page.locator("#open-comparison").isDisabled(), true);
    await buttons.nth(1).click();
    await compareMenu.click();
    await page.getByRole("button", { name: "Сравнить предложения" }).click();
    const dialog = page.getByRole("dialog", { name: "Сравнение предложений" });
    await dialog.waitFor();
    assert.equal(await dialog.locator("thead th").count(), 3);
    await dialog.getByRole("button", { name: "Закрыть" }).click();
    await buttons.nth(2).click();
    await buttons.nth(3).click();
    assert.equal(await buttons.nth(4).isDisabled(), true);
    await compareMenu.click();
    assert.equal(await page.locator("#comparison-count").innerText(), "Выбрано 4 из 4");
    const chosen = await page.locator("#comparison-items span").allTextContents();
    await page.getByRole("button", { name: "Сравнить предложения" }).click();
    const headers = await dialog.locator("thead th").allTextContents();
    assert.equal(headers.length, 5);
    for (const [i, name] of chosen.entries()) assert.ok(headers[i + 1].includes(name));
    assert.equal(await dialog.locator("tbody tr").count(), 8);
    assert.ok(await dialog.locator("#comparison-content").evaluate(region => region.scrollWidth > region.clientWidth));
    await dialog.getByRole("button", { name: "Закрыть" }).click();

    await input.fill("КриптоПро CSP 5.0");
    await page.getByRole("button", { name: "Найти" }).click();
    await page.locator("#results article").first().waitFor();
    assert.deepEqual(await page.locator("#comparison-items span").allTextContents(), chosen);
    await compareMenu.click();
    await page.locator("#comparison-items button").first().click();
    assert.equal(await page.locator("#open-comparison").isDisabled(), false);
    await page.locator("#comparison-items button").first().click();
    assert.equal(await page.locator("#open-comparison").isDisabled(), false);
    await page.locator("#comparison-items button").first().click();
    assert.equal(await page.locator("#open-comparison").isDisabled(), true);
    await page.locator("#comparison-items button").first().click();
    assert.equal(await compareMenu.isVisible(), false);
    await input.fill("антивирус для рабочих станций на год");
    await page.getByRole("button", { name: "Найти" }).click();
    await page.getByRole("button", { name: "Применить: 12 месяцев" }).click();
    await page.locator("#results article").first().waitFor();
    assert.equal(await page.locator("select[name=term]").inputValue(), "12");
    await page.getByRole("link", {name: "Закупки для бизнеса", exact: true}).click();
    await page.waitForURL("**/business?demo=true");
    assert.equal(await input.inputValue(), "антивирус для рабочих станций на год");
    await filters.click();
    await page.locator("select[name=platform]").selectOption("windows");
    await page.getByRole("spinbutton", {name: "Рабочих мест"}).fill("50");
    await page.getByRole("button", {name: "Сохранить профиль закупки"}).click();
    await page.reload();
    assert.equal(await page.locator("select[name=platform]").inputValue(), "windows");
    assert.equal(await page.getByRole("spinbutton", {name: "Рабочих мест"}).inputValue(), "50");
    await input.fill("антивирус для рабочих станций");
    await page.getByRole("button", {name: "Найти"}).click();
    const first = page.locator("#results article").first();
    await first.getByRole("button", {name: "На согласование"}).click();
    await page.getByRole("button", {name: "Запросить КП"}).click();
    await page.getByRole("button", {name: "Открыть письмо"}).waitFor();
    assert.equal(await page.locator("#quote-form input:required").count(), 4);
    assert.equal(await page.locator("#quote-form").evaluate(form => form.checkValidity()), false);
    await page.getByText("Посмотреть запрос", {exact: true}).click();
    assert.match(await page.locator("#quote-text").inputValue(), /покрытие 50 рабочих мест/);
    for (const [button, expected, content] of [
      ["Скачать CSV", "waive-approval.csv", /"Рабочие места".*"50"/s],
      ["Скачать черновик TXT", "waive-quote-request.txt", /покрытие 50 рабочих мест/],
    ]) {
      const started = page.waitForEvent("download");
      await page.getByRole("button", {name: button, exact: true}).click();
      const result = await started;
      assert.equal(result.suggestedFilename(), expected);
      assert.match(await readFile(await result.path(), "utf8"), content);
    }
    await page.route("**/quote/config", route => route.fulfill({json: {
      automatic_delivery: true, recipient: "sales@example.test",
    }}));
    let sent;
    await page.route("**/quote/request", route => {
      sent = route.request().postDataJSON();
      return route.fulfill({json: {sent: true}});
    });
    await page.getByRole("button", {name: "Запросить КП"}).click();
    await page.getByLabel("Имя", {exact: true}).fill("Анна");
    await page.getByLabel("Почта", {exact: true}).fill("anna@example.test");
    await page.getByLabel("Телефон", {exact: true}).fill("+7 999 123 45 67");
    await page.getByLabel("Компания", {exact: true}).fill("Тестовая компания");
    await page.getByRole("button", {name: "Отправить запрос", exact: true}).click();
    await page.getByText("Запрос отправлен.", {exact: true}).waitFor();
    assert.equal(sent.items[0].workplaces, 50);
    assert.equal(sent.email, "anna@example.test");
    await filters.click();
    await page.locator("select[name=platform]").selectOption("linux");
    await input.fill("офисный пакет");
    assert.equal(await page.locator("select[name=platform]").inputValue(), "windows");
    await page.reload();
    await page.getByText("Список на согласование · 1").waitFor();
    assert.ok(process.env.BUNDLE_SMOKE_OFFER);
    await page.getByRole("button", {name: "Удалить профиль"}).click();
    await page.getByRole("spinbutton", {name: "Рабочих мест"}).fill("");
    await filters.click();
    await page.locator("select[name=platform]").selectOption("");
    await page.locator("select[name=term]").selectOption("");
    await input.fill(process.env.BUNDLE_SMOKE_OFFER);
    await page.getByRole("button", {name: "Найти"}).click();
    await page.locator("#results article").first().getByRole("button", {name: "Подобрать комплект"}).click();
    assert.equal(await more.isVisible(), false);
    const bundle = page.getByRole("region", {name: "Дополнения к выбранному товару"});
    await bundle.getByText(/Поддержка ОС: windows/i).first().waitFor();
    await bundle.locator("article:nth-of-type(n+2)").getByRole("button", {name: "На согласование"}).first().click();
    await page.getByText("Список на согласование · 2").waitFor();
    await page.getByRole("link", {name: "К поиску по каталогу", exact: true}).click();
    assert.equal(await page.getByText("Список на согласование · 2").isVisible(), false);
    assert.equal(await input.inputValue(), process.env.BUNDLE_SMOKE_OFFER);
    await page.goto(new URL("/analytics.html", page.url()).href);
    await page.getByLabel("Ключ аналитики").fill(process.env.ANALYTICS_TOKEN);
    await page.getByLabel("Только демо-запросы").check();
    await page.getByRole("button", {name: "Обновить"}).click();
    await page.getByRole("cell", {name: /Сузило выдачу условие «срок лицензии»/}).first().waitFor();
    console.log("Проверены подсказки, сравнение, условия закупки и отчёт по демо-запросам");
  } finally {
    await browser.close();
  }
}
main().catch(error => { console.error(error); process.exit(1); });
